// 발행 문장 끝의 검토·표본 안내 꼬리말만 떼고 본문은 그대로 두는지 확인한다.
import { expect, it } from "vitest";
import { stripReviewNotice } from "../review-notice";

// 문장 끝의 "참고용 — 담당자 검토 필수"를 뗀다.
it("검토 안내 꼬리말을 뗀다", () => {
  expect(
    stripReviewNotice(
      "순간 최대 예상 인원 기준에 따라 수립 대상입니다. 참고용 — 담당자 검토 필수",
    ),
  ).toBe("순간 최대 예상 인원 기준에 따라 수립 대상입니다.");
  expect(
    stripReviewNotice("자체 대규모 기준이며 참고용 — 담당자 검토 필수 입력"),
  ).toBe("자체 대규모 기준이며 입력");
});

// "· 표본 한계로 구간 기준 표시"와 남는 가운뎃점을 함께 정리한다.
it("표본 한계 꼬리말과 남는 가운뎃점을 정리한다", () => {
  expect(
    stripReviewNotice(
      "순간 최대 10,071~32,971명 추정 — 추정 산식 기반 · 표본 한계로 구간 기준 표시",
    ),
  ).toBe("순간 최대 10,071~32,971명 추정 — 추정 산식 기반");
});

// 안내가 없는 문장은 바꾸지 않는다.
it("안내가 없는 문장은 그대로 둔다", () => {
  expect(stripReviewNotice("무대 앞 밀집")).toBe("무대 앞 밀집");
});
