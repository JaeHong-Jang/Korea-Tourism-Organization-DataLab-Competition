// 예산의 중첩 단위와 생략 표기를 원 단위로 계산하고 불명확한 값은 보류한다
import { expect, it } from "vitest";
import { normalizeBudget } from "../src/team/analysis/normalize/budget.js";

// 천을 만의 계수로 곱하고 억과 합산하는 표기를 고정한다
it.each([
  ["2천만원", 20_000_000],
  ["2억 3천만원", 230_000_000],
  ["1억 5천", 150_000_000],
  ["1억 5천원", 100_005_000],
  ["3,000만 원", 30_000_000],
  ["예산은 총 1억 5천만 원", 150_000_000],
  ["1억 5000만원", 150_000_000],
  ["1억 2천5백만원", 125_000_000],
  ["2천5백30만원", 25_300_000],
  ["1.5억원", 150_000_000],
  ["2.5천만원", 25_000_000],
  ["1만 5천원", 15_000],
  ["3,000원", 3_000],
  ["0원", 0],
])("%s를 %i원으로 정규화한다", (text, amount) => {
  expect(normalizeBudget(text)).toBe(amount);
});

// 중복·역순 단위와 범위·근삿값을 확정 예산으로 사용하지 않는다
it.each([
  null,
  "",
  "미정",
  "약 2천만원",
  "2천만원 정도",
  "-2천만원",
  "2천만~3천만원",
  "1억 2억",
  "2만 1억",
  "1천 2천만원",
  "1.2.3억원",
  "0.1원",
  "9007199254740992원",
])("%s는 확인 전까지 보류한다", (text) => {
  expect(normalizeBudget(text)).toBeNull();
});
