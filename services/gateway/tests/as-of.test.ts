// 개최일과 오늘의 한국 날짜 경계에서 예보 기준일을 검증한다
import { describe, expect, it } from "vitest";
import { asOfDate } from "../src/team/analysis/as-of.js";

describe("예보 기준일", () => {
  // 먼 행사는 오늘까지, 가까운 행사는 개최 D-14까지만 자료를 사용한다
  it.each([
    ["2026-09-25T03:00:00Z", "2026-09-25"],
    ["2026-10-10T03:00:00Z", "2026-10-04"],
    ["2026-10-04T03:00:00Z", "2026-10-04"],
    ["2026-09-24T14:59:59Z", "2026-09-24"],
    ["2026-09-24T15:00:00Z", "2026-09-25"],
  ])("오늘 %s의 기준일은 %s", (now, expected) => {
    expect(asOfDate("2026-10-18T19:00:00+09:00", new Date(now))).toBe(expected);
  });

  // UTC에서는 전날인 시작 시각도 개최지의 한국 날짜로 계산한다
  it("개최일도 KST로 정규화한다", () => {
    expect(
      asOfDate("2026-10-17T15:00:00Z", new Date("2026-10-10T00:00:00Z")),
    ).toBe("2026-10-04");
  });
});
