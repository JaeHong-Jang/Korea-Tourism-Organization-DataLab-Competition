# 장소 인덱스 없이 행정 경계만 읽으며 다른 지역의 가까운 도시를 대신 사용하지 않는다.
@lru_cache(maxsize=1)
def weather_gazetteer() -> Gazetteer:
    return Gazetteer(pl.read_parquet(paths.PROCESSED / "admin_dict.parquet"))


# 시군구명과 시도를 함께 써 경기·전남 광주와 강원·경남 고성을 구분한다.
def region_codes(code: str, name: str) -> tuple[str, str | None] | None:
    province = code[:2]
    land = LAND_CODES.get(province)
    if land is None:
        return None
    city_name = name.split()[0].removesuffix("시").removesuffix("군")
    group = land[2] if land[2] in "BG" else land[2:4]
    cities = CITY_CODES[group]
    if province == "51" and city_name in CITY_CODES["D2"]:
        land, cities = "11D20000", CITY_CODES["D2"]
    city = cities.get(city_name)
    if city is None and province in METRO_NAMES and name.endswith("구"):
        city = cities[METRO_NAMES[province]]
    if province in {"11", "26", "29", "30", "31", "36"}:
        city = cities[METRO_NAMES[province]]
    return land, city


# 경계 자료가 없거나 경계선의 양쪽 예보구역이 다르면 추측하지 않고 정보 없음으로 둔다.
def weather_regions(lat: float, lng: float) -> tuple[str, str | None] | None:
    try:
        gazetteer = weather_gazetteer()
        codes = gazetteer.locate(lat, lng)
        matches = {region_codes(code, gazetteer.regions[code]["sigungu_name"]) for code in codes}
    except (OSError, RuntimeError, pl.exceptions.PolarsError):
        return None
    return matches.pop() if len(matches) == 1 else None
